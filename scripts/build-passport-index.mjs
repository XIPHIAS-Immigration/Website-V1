#!/usr/bin/env node
// scripts/build-passport-index.mjs
// -----------------------------------------------------------------------------
// Turns the access matrix into the static artefacts the site reads at build time.
// Mirrors scripts/build-search-index.mjs, and runs from the same prebuild hook.
//
//   in   src/data/passports/access/<CODE>.json   one file per passport
//   out  public/passport-index.json              ranked snapshot for the client
//        src/data/passports/generated-index.ts   typed summary for server render
//
// A missing per-passport file is not an error. It means that passport has no
// verified cells yet, and it is reported as pending rather than scored.
// -----------------------------------------------------------------------------

import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const ACCESS_DIR = path.join(ROOT, "src", "data", "passports", "access");
const TERRITORIES = path.join(ROOT, "src", "data", "passports", "territories.ts");

const WEIGHTS = {
  "visa-free": 1,
  eta: 0.9,
  "visa-on-arrival": 0.7,
  "e-visa": 0.4,
  "visa-required": 0,
  banned: 0,
};
const MIN_COVERAGE = 0.8;

/** Pull the code lists out of the TS module without needing a TS runtime. */
function readTerritories() {
  const source = fs.readFileSync(TERRITORIES, "utf8");
  const grab = (marker) => {
    const start = source.indexOf(marker);
    const end = source.indexOf("];", start);
    return [...source.slice(start, end).matchAll(/code:\s*"([A-Z]{2})"/g)].map((m) => m[1]);
  };
  return {
    destinations: grab("export const destinations"),
    passports: grab("export const passportAuthorities"),
  };
}

function readAccess(code) {
  const file = path.join(ACCESS_DIR, `${code}.json`);
  if (!fs.existsSync(file)) return {};
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    console.warn(`[passport-index] ${code}.json is not valid JSON — treated as empty.`, error.message);
    return {};
  }
}

function summarise(code, access, destinations) {
  const counts = {
    "visa-free": 0, eta: 0, "visa-on-arrival": 0, "e-visa": 0,
    "visa-required": 0, banned: 0, unknown: 0,
  };
  let weighted = 0;
  let verified = 0;
  let total = 0;

  for (const destination of destinations) {
    if (destination === code) continue;
    total += 1;
    const level = access[destination]?.level ?? "unknown";
    counts[level] = (counts[level] ?? 0) + 1;
    if (level === "unknown") continue;
    verified += 1;
    weighted += WEIGHTS[level] ?? 0;
  }

  return {
    code,
    counts,
    weighted,
    openDestinations: counts["visa-free"] + counts.eta + counts["visa-on-arrival"],
    verifiedCells: verified,
    totalCells: total,
    coverage: total ? verified / total : 0,
  };
}

function main() {
  if (!fs.existsSync(ACCESS_DIR)) fs.mkdirSync(ACCESS_DIR, { recursive: true });

  const { destinations, passports } = readTerritories();
  const summaries = passports.map((code) => summarise(code, readAccess(code), destinations));

  const publishable = summaries.filter((s) => s.coverage >= MIN_COVERAGE);
  const best = publishable.reduce((max, s) => Math.max(max, s.weighted), 0);

  const ranked = summaries
    .map((s) => ({
      ...s,
      score: s.coverage >= MIN_COVERAGE && best > 0 ? Math.round((s.weighted / best) * 1000) / 10 : null,
    }))
    .sort((a, b) => (b.score ?? -1) - (a.score ?? -1) || a.code.localeCompare(b.code));

  let rank = 0;
  let previous = null;
  ranked.forEach((entry, index) => {
    if (entry.score === null) {
      entry.rank = null;
      return;
    }
    if (entry.score !== previous) rank = index + 1;
    previous = entry.score;
    entry.rank = rank;
  });

  const snapshot = {
    generatedAt: new Date().toISOString(),
    destinationsTracked: destinations.length,
    passportsTracked: passports.length,
    passportsScored: publishable.length,
    minCoverage: MIN_COVERAGE,
    weights: WEIGHTS,
    passports: ranked,
  };

  fs.writeFileSync(path.join(ROOT, "public", "passport-index.json"), JSON.stringify(snapshot));

  const generated = `// GENERATED by scripts/build-passport-index.mjs — do not edit.
import type { MobilityResult } from "@/lib/passports/mobility-score";

export const passportSnapshot = ${JSON.stringify(
    { ...snapshot, passports: undefined },
    null,
    2,
  )} as const;

export const rankedPassports: Array<MobilityResult & { rank: number | null }> = ${JSON.stringify(
    ranked,
    null,
    2,
  )};
`;
  fs.writeFileSync(path.join(ROOT, "src", "data", "passports", "generated-index.ts"), generated);

  console.log(
    `[passport-index] ${publishable.length}/${passports.length} passports scored across ` +
      `${destinations.length} destinations. ${passports.length - publishable.length} pending verification.`,
  );
}

main();
